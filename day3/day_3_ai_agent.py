def is_supported(crop: str) -> bool:
    """Check whether a crop is supported."""
    return crop.lower().strip() == "tomato"


def get_service(service: str) -> str:
    """Return information about a supported service."""

    services = {
        "scan": "Tomato leaf disease detection",
        "weather": "Environmental weather analysis",
        "risk": "Preliminary disease risk assessment"
    }

    return services.get(
        service.lower().strip(),
        "Service not available"
    )


