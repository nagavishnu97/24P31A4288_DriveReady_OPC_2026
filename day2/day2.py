import json,functools
from openai import RateLimitError,APIConnectionError
MODEL = "openai/gpt-oss-120b"

MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}
SYSTEM = f"""
ROLE:
You are a friendly Sweet Crumbs bakery assistant.

FACTS:
Menu: {json.dumps(MENU)}
Orders require 24 hours' notice.
Eggless versions are available.

RULES:
Never promise a delivery time.
If unsure, check with the owner.
Remember customer names and orders.

FORMAT:
Under 50 words.
Reply in English or Telugu.
"""
def log_call(func):

    @functools.wraps(func)
    def wrapper(*args, **kwargs):

        result = func(*args, **kwargs)

        print(f"[log] {func.__name__}{args} -> {result!r}")

        return result

    return wrapper
@log_call
def get_price(item: str, qty: int = 1) -> int:
    """Calculate the total price of an order."""

    return MENU[item.lower().strip()] * qty
history = [
    {
        "role": "system",
        "content": SYSTEM
    }
]

MAX_TURNS = 8
def chat(user_text: str) -> str:

    history.append({
        "role": "user",
        "content": user_text
    })

    recent = [history[0]] + history[1:][-MAX_TURNS:]

    try:
        response = client.chat.completions.create(
            model=MODEL,
            messages=recent,
            temperature=0.3
        )

        reply = response.choices[0].message.content

    except RateLimitError:
        reply = "Server busy. Please try again."

    except APIConnectionError:
        reply = "Unable to connect to the server."

    history.append({
        "role": "assistant",
        "content": reply
    })

    return reply
print("Total for 6 cupcakes:", get_price("cupcake", 6))
while True:
    text = input("You: ")
    if text.lower().strip() in ("bye", "exit", "quit"):
        print("Bot: Thank you for visiting Sweet Crumbs!")
        break
    print("Bot:", chat(text))

